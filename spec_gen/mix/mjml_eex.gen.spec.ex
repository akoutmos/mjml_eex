defmodule Mix.Tasks.MjmlEex.Gen.Spec do
  @shortdoc "Regenerates the MJML spec from the MJML packages pinned in spec_gen/"

  @moduledoc """
  Regenerates `MjmlEEx.Spec.Generated` and the type test vectors from the MJML
  packages pinned in `spec_gen/package.json`.

      mix mjml_eex.gen.spec

  This is a dev-only task and requires Node. It installs the pinned packages
  with `npm ci` if needed, runs `spec_gen/dump.js`, and writes:

  - `lib/mjml_eex/spec/generated.ex`
  - `test/fixtures/spec/type_vectors.json`
  - `test/fixtures/validation/mjml_validator.json`, MJML's own validator results for the
    validation fixtures in `test/fixtures/validation/`
  - `test/fixtures/includes/mjml_includes.json`, how MJML's parser expands the `mj-include`
    fixtures in `test/fixtures/includes/`

  Both files are checked in, so users and CI never need Node. To move to a new
  MJML version, update the versions in `spec_gen/package.json`, run `npm install`
  in `spec_gen/`, and then run this task.
  """

  use Mix.Task

  @spec_gen_dir "spec_gen"
  @generated_path "lib/mjml_eex/spec/generated.ex"
  @vectors_path "test/fixtures/spec/type_vectors.json"
  @validation_dir "test/fixtures/validation"
  @validation_path "test/fixtures/validation/mjml_validator.json"
  @includes_dir "test/fixtures/includes"
  @includes_path "test/fixtures/includes/mjml_includes.json"

  @impl Mix.Task
  def run(_args) do
    unless System.find_executable("node") do
      Mix.raise("mix mjml_eex.gen.spec requires Node")
    end

    unless File.dir?(Path.join(@spec_gen_dir, "node_modules")) do
      Mix.shell().info("Installing the pinned MJML packages with npm ci")
      {_, 0} = System.cmd("npm", ["ci", "--no-audit", "--no-fund"], cd: @spec_gen_dir, into: IO.stream())
    end

    spec =
      case System.cmd("node", [Path.join(@spec_gen_dir, "dump.js"), @vectors_path], stderr_to_stdout: false) do
        {json, 0} -> JSON.decode!(json)
        {_, status} -> Mix.raise("spec_gen/dump.js exited with status #{status}")
      end

    File.mkdir_p!(Path.dirname(@generated_path))
    File.write!(@generated_path, render(spec))

    run_node!("validate.js", [@validation_dir, @validation_path])
    run_node!("includes.js", [@includes_dir, "test/test_includes", @includes_path])

    Mix.shell().info(
      "Generated #{@generated_path}, #{@vectors_path}, #{@validation_path} and #{@includes_path} " <>
        "from MJML #{spec["mjml_version"]}"
    )
  end

  defp run_node!(script, args) do
    case System.cmd("node", [Path.join(@spec_gen_dir, script) | args]) do
      {_, 0} -> :ok
      {_, status} -> Mix.raise("spec_gen/#{script} exited with status #{status}")
    end
  end

  @doc false
  def render(spec) do
    version = spec["mjml_version"]

    components =
      spec["components"]
      |> Map.new(fn component ->
        {component["name"],
         %{
           kind: String.to_atom(component["kind"]),
           ending_tag: component["ending_tag"],
           raw_element: component["raw_element"],
           allowed_attributes: component["allowed_attributes"],
           default_attributes: component["default_attributes"]
         }}
      end)

    dependencies =
      Map.new(spec["dependencies"], fn
        {parent, "any"} -> {parent, :any}
        {parent, children} -> {parent, children}
      end)

    """
    # This file is generated by `mix mjml_eex.gen.spec` from MJML #{version}. Do not edit it by hand.
    # MJML (https://github.com/mjmlio/mjml) is MIT licensed: Copyright (c) 2016 Mailjet SAS, https://mjml.io
    defmodule MjmlEEx.Spec.Generated do
      # The MJML component spec, generated from MJML #{version} (`mjml-preset-core`, `mjml-core` and
      # `mjml-validator`).
      #
      # Hand-written additions, such as the elements that are not registered components and
      # the components that mrml does not implement, live in `MjmlEEx.Spec.Overlay`.
      @moduledoc false

      @typedoc "A registered MJML component."
      @type component :: %{
              kind: :head | :body,
              ending_tag: boolean(),
              raw_element: boolean(),
              allowed_attributes: %{String.t() => String.t()},
              default_attributes: %{String.t() => String.t()}
            }

      @doc "The MJML version the spec was generated from."
      @spec mjml_version() :: String.t()
      def mjml_version, do: #{literal(version)}

      @doc \"\"\"
      The registered components, keyed by tag name. `allowed_attributes` maps each attribute to
      its MJML type string (see `MjmlEEx.Spec.Types`). Ending tags hold raw HTML or text
      and cannot contain other MJML components.
      \"\"\"
      @spec components() :: %{String.t() => component()}
      def components, do: #{literal(components)}

      @doc \"\"\"
      The children each tag allows. `:any` means any tag is allowed. Children that are not
      registered components are not checked by MJML's validator.
      \"\"\"
      @spec dependencies() :: %{String.t() => [String.t()] | :any}
      def dependencies, do: #{literal(dependencies)}

      @doc \"\"\"
      The parents in `dependencies/0`, in MJML's order. MJML's validator lists the valid
      parents in this order in its error messages.
      \"\"\"
      @spec dependency_order() :: [String.t()]
      def dependency_order, do: #{literal(spec["dependency_order"])}

      @doc "The attributes that every component accepts."
      @spec global_attributes() :: [String.t()]
      def global_attributes, do: #{literal(spec["global_attributes"])}

      @doc "Tags that MJML allows even though they are not registered components."
      @spec component_less_tags() :: [String.t()]
      def component_less_tags, do: #{literal(spec["component_less_tags"])}

      @doc "The named colors accepted by the `color` type."
      @spec named_colors() :: [String.t()]
      def named_colors, do: #{literal(spec["named_colors"])}

      @doc "Every distinct attribute type string used by the components."
      @spec type_strings() :: [String.t()]
      def type_strings, do: #{literal(spec["type_strings"])}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  # Render a term as Elixir source with map keys sorted, so the output is stable
  defp literal(map) when is_map(map) do
    entries =
      map
      |> Enum.sort()
      |> Enum.map_join(", ", fn
        {key, value} when is_atom(key) -> "#{key}: #{literal(value)}"
        {key, value} -> "#{literal(key)} => #{literal(value)}"
      end)

    "%{#{entries}}"
  end

  defp literal(list) when is_list(list), do: "[" <> Enum.map_join(list, ", ", &literal/1) <> "]"
  defp literal(term), do: inspect(term, printable_limit: :infinity, limit: :infinity)
end
